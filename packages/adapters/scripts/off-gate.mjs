// The hook entry the plugin registers: a few lines that return before the engine loads when the mode is off (the default),
// so an installed-but-off hook costs one bare node start. Anything else hands over to the full bundle, argv intact.
// One generator, two callers: this package's bin/ (scripts/build-bin.mjs) and the Claude Code plugin's bin/ (build-plugin.mjs).
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'

export const OFF_GATE = 'riposte-action-hook.mjs'
export const ENGINE = 'riposte-action.mjs'

/** Write the off-gate into `binDir`, next to the engine bundle. `by` and `see` only fill in the generated header comment. */
export function writeOffGate(binDir, { by = 'scripts/build-bin.mjs', see = 'src/claude-code.ts' } = {}) {
  writeFileSync(join(binDir, OFF_GATE), `#!/usr/bin/env node
// Generated by ${by}. Off unless RIPOSTE_ACTION_HOOK is record-only or on (see ${see}).
const mode = (process.env.RIPOSTE_ACTION_HOOK ?? '').trim().toLowerCase()
if (mode === 'record-only' || mode === 'on') await import('./${ENGINE}')
else if (mode && mode !== 'off') console.error('riposte-action: RIPOSTE_ACTION_HOOK="' + process.env.RIPOSTE_ACTION_HOOK + '" is not one of off | record-only | on; staying off')
`)
}
