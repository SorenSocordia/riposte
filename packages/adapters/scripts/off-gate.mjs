// The hook entry the plugin registers: a few lines that return before the engine loads when the mode is off (the default),
// so an installed-but-off hook costs one bare node start. Anything else hands over to the full bundle, argv intact.
// Governance (RIPOSTE_GOV_*, src/governance.ts) also hands over: when any RIPOSTE_GOV* variable is set, or governance is
// EXPECTED here (RIPOSTE_GOV_EXPECTED, or a governance.json marker beside this file or in ~/.riposte/), the engine must run
// on every call whatever RIPOSTE_ACTION_HOOK says, because governance fails closed and the off-gate must never skip it.
//
// Before anything else, the off-gate removes every RIPOSTE_* setting this hook does not read (src/governance.ts
// HOOK_ENV_ACCEPT['claude-code'], plus every RIPOSTE_GOV* name), so an inherited RIPOSTE_LEDGER_UNLOCKED cannot turn the
// receipts ledger's single-writer lock off inside the hook. The names it removed (never values) go on governance receipts.
//
// When governance is configured or expected and the engine bundle does not load (missing, unreadable) or throws, the
// off-gate denies: the PreToolUse deny JSON on stdout (governance.engine_unavailable), the reason on stderr, exit 2.
// Claude Code reads that JSON on every exit code, and exit 2 blocks the tool call even without it. No receipt can be
// written without the engine; the reason is in the host's transcript instead.
//
// THE ACTION POLICY'S SAFEST RUNG (2026-10-05, src/degraded.ts). A RIPOSTE_ACTION_HOOK that is set but is not off hands over
// too: record-only and on as before, and a misspelling, which the engine treats as a policy error (consequential calls held
// with a typed fix, others run on the record) instead of staying off. Without governance, when the engine does not load in
// an enforcing mode (on, or a misspelling), the off-gate applies the same rung itself, without a receipt: it reads the
// tool's rule from RIPOSTE_ACTION_POLICY when it can (a parseable policy that does not name the tool lets it run), else
// the tool's name (WORDS), and denies a consequential call (exit 0, the deny JSON). In record-only, or with the operator's
// opt-out RIPOSTE_ACTION_ON_ERROR=open, a failed engine fails the way it always did. Hosts that ignore all this: none of the
// other hosts runs the off-gate. Codex, Cursor and OpenCode load their own one-file bins, and when one of those cannot
// start, the host decides: Codex continues the tool call, Cursor blocks only when the hook entry sets "failClosed": true,
// OpenCode skips a plugin that fails to load.
// One generator, two callers: this package's bin/ (scripts/build-bin.mjs) and the Claude Code plugin's bin/ (build-plugin.mjs).
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'

export const OFF_GATE = 'riposte-action-hook.mjs'
export const ENGINE = 'riposte-action.mjs'
/** The governance variables (src/governance.ts GOV_ENV_KEYS): any one set hands over to the engine (so does any RIPOSTE_GOV* name). */
export const GOV_KEYS = ['RIPOSTE_GOV_AGENT', 'RIPOSTE_GOV_CHARTER', 'RIPOSTE_GOV_LEDGER', 'RIPOSTE_GOV_CHECKER', 'RIPOSTE_GOV_INBOX', 'RIPOSTE_GOV_RECORDER_KEY', 'RIPOSTE_GOV_RECEIPTS', 'RIPOSTE_GOV_TIMEOUT_MS']
/** The RIPOSTE_* settings the Claude Code hook reads (src/governance.ts HOOK_ENV_ACCEPT['claude-code'] and GOV_EXPECTED_ENV). */
export const ACCEPT = ['RIPOSTE_ACTION_HOOK', 'RIPOSTE_ACTION_POLICY', 'RIPOSTE_ACTION_LEDGER', 'RIPOSTE_LEDGER', 'RIPOSTE_ACTION_ON_ERROR', 'RIPOSTE_GOV_EXPECTED']
/** The governance marker's file name (src/governance.ts GOV_MARKER_FILE). */
export const MARKER = 'governance.json'
/** The words that make a tool name consequential (src/degraded.ts CONSEQUENTIAL_WORDS; a test holds the two equal). */
export const WORDS = [
  'pay', 'pays', 'paid', 'payment', 'payments', 'payout', 'payouts', 'payroll', 'transfer', 'transfers', 'wire', 'wires', 'remit',
  'remittance', 'refund', 'refunds', 'disburse', 'disbursement', 'charge', 'charges', 'withdraw', 'withdrawal', 'settle',
  'settlement', 'capture', 'purchase', 'buy', 'sell', 'trade', 'ach', 'sepa', 'swift', 'apply', 'approve', 'submit', 'filing',
  'lodge',
]

/** Write the off-gate into `binDir`, next to the engine bundle. `by` and `see` only fill in the generated header comment. */
export function writeOffGate(binDir, { by = 'scripts/build-bin.mjs', see = 'src/claude-code.ts' } = {}) {
  writeFileSync(join(binDir, OFF_GATE), `#!/usr/bin/env node
// Generated by ${by}. Off unless RIPOSTE_ACTION_HOOK is set (record-only, on, or a misspelling: a policy error the engine
// holds on the safest rung, see src/degraded.ts), or governance is configured or expected (see ${see}).
import { existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
// Only the RIPOSTE_* settings this hook reads; every other one is removed before anything else runs (names kept for receipts,
// sorted: the environment's own order differs by platform).
const accept = new Set(${JSON.stringify(ACCEPT)})
const stripped = Object.keys(process.env).filter((k) => { const K = k.toUpperCase(); return K.startsWith('RIPOSTE_') && !accept.has(K) && !K.startsWith('RIPOSTE_GOV') }).sort()
for (const k of stripped) delete process.env[k]
if (stripped.length) globalThis[Symbol.for('riposte.hook.env_stripped')] = stripped
const env = (k) => (process.env[k] ?? '').trim()
const mode = env('RIPOSTE_ACTION_HOOK').toLowerCase()
const governance = Object.keys(process.env).some((k) => /^RIPOSTE_GOV/i.test(k) && k.toUpperCase() !== 'RIPOSTE_GOV_EXPECTED' && env(k) !== '')
const home = env('HOME') || env('USERPROFILE')
const expected = (env('RIPOSTE_GOV_EXPECTED') !== '' && !/^(0|false|no|off)$/i.test(env('RIPOSTE_GOV_EXPECTED')))
  || existsSync(new URL('./${MARKER}', import.meta.url)) || (home !== '' && existsSync(join(home, '.riposte', '${MARKER}')))
if ((mode !== '' && mode !== 'off') || governance || expected) {
  if (stripped.some((k) => k.toUpperCase() === 'RIPOSTE_LEDGER_UNLOCKED')) console.error('riposte-action: an inherited RIPOSTE_LEDGER_UNLOCKED was ignored; the receipts ledger keeps its single-writer lock')
  try { await import('./${ENGINE}') } catch (e) {
    const why = String(e && e.message || e).replace(/\\s+/g, ' ').slice(0, 300)
    if (governance || expected) {
      const reason = 'Riposte governance denied this call: governance.engine_unavailable: the hook engine (${ENGINE}) did not load or failed (' + why + '). Governance is configured or expected here, so no tool call runs until the hook is repaired. No receipt could be written. Tell the person.'
      process.stdout.write(JSON.stringify({ hookSpecificOutput: { hookEventName: 'PreToolUse', permissionDecision: 'deny', permissionDecisionReason: reason } }) + '\\n')
      process.stderr.write(reason + '\\n')
      process.exitCode = 2
    } else if (mode === 'record-only' || env('RIPOSTE_ACTION_ON_ERROR').toLowerCase() === 'open') throw e
    else {
      // The safest rung without the engine (an equipment error, src/degraded.ts): a consequential call is denied, any other
      // proceeds. No receipt can be written without the engine; the reason is on stderr and, for a denial, in the transcript.
      let hook = {}
      try { const x = JSON.parse(readFileSync(0, 'utf8')); if (x && typeof x === 'object' && !Array.isArray(x)) hook = x } catch {}
      const tool = typeof hook.tool_name === 'string' ? hook.tool_name : undefined
      let rules
      try { const p = JSON.parse(readFileSync(env('RIPOSTE_ACTION_POLICY'), 'utf8')); if (Array.isArray(p.actions)) rules = p.actions } catch {}
      const rule = rules && tool !== undefined ? rules.find((a) => a && a.tool === tool) : undefined
      const words = tool === undefined ? [] : tool.replace(/([a-z0-9])([A-Z])/g, '$1 $2').split(/[^A-Za-z0-9]+/).map((w) => w.toLowerCase()).filter(Boolean)
      const own = tool === undefined ? [] : (tool.split('__').pop() || '').replace(/([a-z0-9])([A-Z])/g, '$1 $2').split(/[^A-Za-z0-9]+/).map((w) => w.toLowerCase()).filter(Boolean)
      const consequential = tool === undefined ? true
        : rule ? !(rule.level === 'record' || rule.level === 'advise')
        : rules ? false
        : words.some((w) => ${JSON.stringify(WORDS)}.includes(w)) || own[0] === 'file'
      const note = 'riposte-action: governance degraded, policy.error: the hook engine (${ENGINE}) did not load or failed (' + why + '); '
      if (!consequential || hook.hook_event_name !== undefined && hook.hook_event_name !== 'PreToolUse') process.stderr.write(note + 'this call proceeds (no receipt can be written). Fix: rebuild or reinstall the plugin so bin/${ENGINE} is beside this file.\\n')
      else {
        const reason = 'Riposte held this ' + (tool || 'tool') + ' call: governance degraded, policy.error: the hook engine (${ENGINE}) did not load (' + why + '). While the action policy cannot be applied, calls that move money or file something are held and other calls proceed. Fix: rebuild or reinstall the plugin so bin/${ENGINE} is beside the hook; then check the setup with riposte-action --doctor. This call did not run. Do not retry it; tell the person what is held and why.'
        process.stdout.write(JSON.stringify({ hookSpecificOutput: { hookEventName: 'PreToolUse', permissionDecision: 'deny', permissionDecisionReason: reason }, systemMessage: 'Riposte: governance degraded (policy.error). ' + (tool || 'This tool call') + ' is held until the hook engine is restored.' }) + '\\n')
        process.stderr.write(note + 'this call is held.\\n')
      }
    }
  }
}
`)
}
