/**
 * Typed channels (schema v0.1) — VERDICT vs COUNSEL. Riposte speaks on exactly two channels, and they never mix:
 *
 *   VERDICT  checked against a binding source and evidenced. A deterministic proof object (see schema.ts) that
 *            replays byte-for-byte. It NEVER flexes: no tact, no timing, no audience changes what it says. Every FAIL is
 *            shown with its evidence and a dispute path at every rung; it HOLDS the action at gate and autonomy
 *            (notices.ts).
 *   COUNSEL  generated: a miner candle, "you might also check X", a proposed ruling, or a JUDGEMENT-TIER (REASONED)
 *            finding. It carries `provenance.type: 'GENERATED'`, the JUDGE RESULTS that justified surfacing it,
 *            `dismissible: true` and `holds_action: false`. Advisories carry a `strength` ('strong' | 'moderate' | 'note');
 *            a strong advisory is prominent, lets people and agents proceed with the data, and is always shown with the
 *            evidence it rests on and a dispute path. It is advice to a person, never a finding.
 *
 * The guard is the point: COUNSEL can never be rendered or serialized as a VERDICT. `assertVerdict` refuses anything
 * generated (a `channel: 'COUNSEL'` tag OR a GENERATED provenance, whatever else it claims), anything carrying a
 * judgement-tier finding, and anything that is not a well-formed, input-bound, evidenced proof object.
 *
 * ADDITIVE, like accuracy.ts: `stampVerdictChannel` adds `channel: 'VERDICT'` to an existing verdict. The field is not in
 * `verdict_id`, and verify() does not emit it by default, so every existing verdict, verdict_id and golden hash is unchanged.
 *
 * COUNSEL is generated by deterministic code (the miner, the judges, the opinion renderer) or by a reasoning layer that
 * stands OUTSIDE verify. Never by a language model inside verify: the verifier verifies; it does not converse.
 */

import { hashOf } from './canonical.js'
import type { ClaimVerdict, Evidence, Verdict } from './schema.js'
import { deriveVerdictId } from '../protocol/verdict-id.js'
import type { JudgedCandidate, MineReport } from '../mine/types.js'
import { verdictFindings, disputeCommand } from './notices.js'

export type Channel = 'VERDICT' | 'COUNSEL'
export type Strength = 'strong' | 'moderate' | 'note'
export const STRENGTHS: readonly Strength[] = ['strong', 'moderate', 'note']

/** One judge's finding about a piece of counsel: what it measured, and whether the item cleared it. */
export interface JudgeResult {
  /** The judge's name, e.g. the miner's CONSISTENCY / GROUNDING / NOVELTY. */
  judge: string
  passed: boolean
  /** What the judge measured and the gate it applied, in words. */
  detail: string
  /** The numbers behind the finding (counts, p-values, gates), so it can be re-checked. */
  stats?: Record<string, number>
}

/** Where generated material came from. `type` is literally 'GENERATED': the label that keeps it off the VERDICT channel. */
export interface GeneratedProvenance {
  type: 'GENERATED'
  /** The generator, e.g. 'riposte-mine', or the reasoning layer that produced a judgement-tier finding. */
  generator: string
  generator_version: string
  /** Hash of the data it was generated from (the mined case table; the verdict's input_hash) — the replay anchor. */
  source_hash: string
}

export interface Counsel {
  channel: 'COUNSEL'
  counsel_version: 'counsel-v0'
  /** Deterministic: the first 32 hex of sha256 over the canonical counsel body (everything but this field). */
  counsel_id: string
  kind: 'CANDLE' | 'SUGGESTION' | 'ADVISORY'
  /** How prominently to show it. Required on an ADVISORY. */
  strength?: Strength
  /** One line: what is being suggested. */
  title: string
  /** The suggestion in words. Advisory only. */
  body: string
  /** Machine-readable payload (for a CANDLE: the rule's spec; for an ADVISORY: the finding it carries). */
  subject?: unknown
  /** The evidence it rests on. Always present, and non-empty, on a strong advisory. */
  evidence?: Evidence[]
  /** How a person disputes it. Always present on an ADVISORY. */
  dispute?: { verdict_id: string; claim_id: string; command: string }
  provenance: GeneratedProvenance
  /** The judge results that justified surfacing it. Never empty, and every one passed. */
  judges: JudgeResult[]
  /** Always true: counsel may be dismissed without cost or explanation. */
  dismissible: true
  /** Always false: counsel never holds an action. People and agents may proceed with the data. */
  holds_action: false
}

/** Thrown when something tries to cross from COUNSEL to VERDICT, or to present a non-proof as a VERDICT. */
export class ChannelViolation extends Error {
  constructor(message: string) {
    super(message)
    this.name = 'ChannelViolation'
  }
}

const isObj = (x: unknown): x is Record<string, unknown> => x !== null && typeof x === 'object' && !Array.isArray(x)

/**
 * Which channel an object speaks on. Anything carrying a COUNSEL tag or a GENERATED provenance is COUNSEL, whatever else
 * it claims (a generated thing wearing verdict fields is still generated). A verdict-shaped object is VERDICT. Anything
 * else: undefined.
 */
export function channelOf(x: unknown): Channel | undefined {
  if (!isObj(x)) return undefined
  if (x.channel === 'COUNSEL') return 'COUNSEL'
  const prov = x.provenance
  if (isObj(prov) && prov.type === 'GENERATED') return 'COUNSEL'
  if (typeof x.verdict_id === 'string' && Array.isArray(x.claims) && typeof x.outcome === 'string') return 'VERDICT'
  return undefined
}

/**
 * The first reason a proof object fails the checks, or undefined. With `allowReasoned`, judgement-tier findings are
 * tolerated (used only to replay-bind a verdict whose REASONED finding is being disputed; such a verdict is still never
 * stamped VERDICT).
 */
export function proofProblem(x: unknown, opts: { allowReasoned?: boolean } = {}): string | undefined {
  if (channelOf(x) === 'COUNSEL') {
    return 'COUNSEL can never be presented as a VERDICT: it is generated (channel COUNSEL or provenance GENERATED) and dismissible, not checked against a binding source'
  }
  if (!isObj(x) || channelOf(x) !== 'VERDICT') return 'not a verdict: a VERDICT is a proof object with verdict_id, outcome and claims'
  if (x.channel !== undefined && x.channel !== 'VERDICT') return `a verdict cannot carry channel ${JSON.stringify(x.channel)}`
  const v = x as unknown as Verdict
  if (v.replayable !== true) return `verdict ${v.verdict_id} does not assert replayable: true`
  if (typeof v.input_hash !== 'string' || !isObj(v.ruleset) || typeof v.engine_version !== 'string') {
    return `verdict ${v.verdict_id} lacks the reproducibility contract (input_hash, ruleset, engine_version)`
  }
  // Engine 0.2.0 (2026-10-03): the id derives from the remedy table hash too, when the verdict carries one.
  const rth = typeof v.remedy_table_hash === 'string' ? v.remedy_table_hash : undefined
  const expected = deriveVerdictId(v.input_hash, v.ruleset, v.engine_version, rth)
  if (expected !== v.verdict_id) {
    return `verdict ${v.verdict_id} is not bound to its inputs: its id does not derive from input_hash + ruleset@version + engine_version${rth !== undefined ? ' + remedy_table_hash' : ''} (expected ${expected})`
  }
  for (const c of v.claims) {
    if (c.outcome !== 'PASS' && c.outcome !== 'FAIL') continue
    if (!Array.isArray(c.evidence) || c.evidence.length === 0) return `claim ${c.claim_id} is ${c.outcome} without evidence; an unevidenced finding is not a VERDICT`
    if (c.tier !== 'DETERMINISTIC' && !opts.allowReasoned) {
      return `claim ${c.claim_id} is a judgement-tier (${c.tier}) finding: judgement is COUNSEL (an advisory with a strength), never a VERDICT. Surface it with counselFromReasoned`
    }
  }
  return undefined
}

/**
 * The VERDICT-channel gate. Passes only a proof object that earns the channel: not generated; verdict-shaped with
 * `replayable: true`; bound to its inputs (verdict_id re-derives); every PASS/FAIL claim evidenced; and every PASS/FAIL
 * claim DETERMINISTIC (judgement is COUNSEL). Throws ChannelViolation otherwise.
 */
export function assertVerdict(x: unknown): asserts x is Verdict {
  const problem = proofProblem(x)
  if (problem) throw new ChannelViolation(problem)
}

/**
 * Stamp `channel: 'VERDICT'` onto a verdict that earns it (see assertVerdict). Additive metadata: verdict_id and every
 * other field are unchanged, so replay-binding holds (the accuracy.ts pattern).
 */
export function stampVerdictChannel(verdict: Verdict): Verdict {
  assertVerdict(verdict)
  return verdict.channel === 'VERDICT' ? verdict : { ...verdict, channel: 'VERDICT' }
}

/** Serialize as a VERDICT (pretty JSON, channel stamped). Throws ChannelViolation for COUNSEL or a non-proof. */
export function serializeVerdict(x: unknown): string {
  assertVerdict(x)
  return JSON.stringify(stampVerdictChannel(x), null, 2)
}

/**
 * Render as a VERDICT (Markdown card). Every FAIL and ABSTAIN is shown with the evidence it rests on and its own dispute
 * path. The card is rung-free: whether the action is held is the rung's (actionNotice). Throws ChannelViolation for COUNSEL
 * or a non-proof.
 */
export function renderVerdict(x: unknown): string {
  assertVerdict(x)
  const v = x
  const n = verdictFindings(v)
  const lines = [
    `**VERDICT** · **${v.outcome}** · ruleset \`${v.ruleset.id}@${v.ruleset.version}\` · engine ${v.engine_version} · verdict \`${v.verdict_id}\``,
    '',
    `> Checked against the supplied sources and evidenced; replayable byte-for-byte. ${v.coverage.claims_checked} of ${v.coverage.claims_total} claim(s) decided (${v.coverage.claims_pass} PASS · ${v.coverage.claims_fail} FAIL · ${v.coverage.claims_insufficient} can't-tell).${n.outcome !== 'PASS' ? ' Every finding below can be disputed. At record and advise it is surfaced, not held; at gate and autonomy it holds the action until a person resolves it.' : ''}`,
    '',
  ]
  for (const f of n.findings) {
    const why = f.outcome === 'FAIL' ? f.explanation : `${f.insufficiency?.reason ?? 'INSUFFICIENT_DATA'}: ${f.insufficiency?.detail ?? f.explanation}`
    lines.push(`- ${f.outcome === 'FAIL' ? '✗' : '⚠'} \`${f.claim_id}\` (${f.rule_name}): ${why}`)
    for (const e of f.evidence) {
      const where = e.locator.kind === 'field' ? `${e.locator.source}:${e.locator.path}` : `span ${e.locator.source_hash.slice(0, 12)}…`
      lines.push(`  - \`${where}\` = ${JSON.stringify(e.value)} · confidence ${e.confidence}`)
    }
    lines.push(`  - dispute: \`${f.dispute}\``)
  }
  if (n.findings.length === 0) lines.push('- every claim held')
  lines.push('')
  return lines.join('\n')
}

// ── COUNSEL ───────────────────────────────────────────────────────────────────────────────────────────────────────────

export interface CounselInput {
  kind: Counsel['kind']
  strength?: Strength
  title: string
  body: string
  subject?: unknown
  evidence?: Evidence[]
  dispute?: Counsel['dispute']
  provenance: GeneratedProvenance
  judges: JudgeResult[]
}

/**
 * Build a COUNSEL item. Refuses (throws) anything that has not earned surfacing: no judges, a judge that did not pass,
 * a provenance that is not GENERATED, or an empty source anchor. An ADVISORY must declare its strength and a dispute
 * path; a strong one must carry the evidence it rests on. The id is derived from the content.
 */
export function makeCounsel(input: CounselInput): Counsel {
  if (!input.provenance || input.provenance.type !== 'GENERATED') throw new ChannelViolation('counsel must carry provenance.type GENERATED')
  if (!input.provenance.generator || !input.provenance.generator_version || !input.provenance.source_hash) {
    throw new ChannelViolation('counsel provenance needs generator, generator_version and source_hash (the replay anchor)')
  }
  if (!Array.isArray(input.judges) || input.judges.length === 0) throw new ChannelViolation('counsel must carry the judge results that justified surfacing it')
  const failed = input.judges.filter(j => j.passed !== true)
  if (failed.length > 0) throw new ChannelViolation(`counsel cannot be surfaced: judge(s) ${failed.map(j => j.judge).join(', ')} did not pass`)
  if (!input.title.trim() || !input.body.trim()) throw new ChannelViolation('counsel needs a title and a body')
  if (input.strength !== undefined && !STRENGTHS.includes(input.strength)) throw new ChannelViolation(`strength must be one of ${STRENGTHS.join(', ')}`)
  if (input.kind === 'ADVISORY') {
    if (input.strength === undefined) throw new ChannelViolation('an advisory must declare its strength (strong | moderate | note)')
    if (!input.dispute || !input.dispute.verdict_id || !input.dispute.claim_id || !input.dispute.command) throw new ChannelViolation('an advisory must carry a dispute path')
  }
  if (input.strength === 'strong' && (!Array.isArray(input.evidence) || input.evidence.length === 0)) {
    throw new ChannelViolation('a strong advisory is always shown with the evidence it rests on; it has none')
  }
  const body: Omit<Counsel, 'counsel_id'> = {
    channel: 'COUNSEL',
    counsel_version: 'counsel-v0',
    kind: input.kind,
    ...(input.strength !== undefined ? { strength: input.strength } : {}),
    title: input.title,
    body: input.body,
    ...(input.subject !== undefined ? { subject: input.subject } : {}),
    ...(input.evidence !== undefined ? { evidence: input.evidence.map(e => ({ ...e })) } : {}),
    ...(input.dispute !== undefined ? { dispute: { ...input.dispute } } : {}),
    provenance: { ...input.provenance },
    judges: input.judges.map(j => ({ ...j, ...(j.stats ? { stats: { ...j.stats } } : {}) })),
    dismissible: true,
    holds_action: false,
  }
  return { ...body, counsel_id: hashOf(body).slice(0, 32) }
}

/** True for a well-formed COUNSEL item whose id still derives from its content. */
export function isCounsel(x: unknown): x is Counsel {
  if (!isObj(x) || x.channel !== 'COUNSEL' || x.counsel_version !== 'counsel-v0') return false
  const { counsel_id, ...body } = x
  return typeof counsel_id === 'string' && hashOf(body).slice(0, 32) === counsel_id
}

/**
 * A miner CANDLE as COUNSEL. The three judges of the mining gauntlet (docs/BENCHMARK-MINE.md) become the judge
 * results, re-checked here against the report's own gates: a candle whose recorded numbers do not clear them is refused.
 * Only fate CANDLE can be surfaced; the morgue stays in the morgue.
 */
export function counselFromCandle(report: MineReport, candle: JudgedCandidate): Counsel {
  if (candle.fate !== 'CANDLE') throw new ChannelViolation(`only a CANDLE can be surfaced as counsel (${candle.id} is ${candle.fate})`)
  const o = report.options
  const approves = candle.decidable - candle.decidable_holds
  const allowed = Math.floor(o.maxApprovedViolationRate * approves + 1e-9)
  const newHolds = candle.new_holds ?? 0
  const judges: JudgeResult[] = [
    {
      judge: 'CONSISTENCY',
      passed: candle.approved <= allowed,
      detail: `${candle.approved} approved case(s) violate it, of ${approves} decidable approvals (allowed ${allowed} at max rate ${o.maxApprovedViolationRate})`,
      stats: { approved: candle.approved, decidable_approves: approves, allowed },
    },
    {
      judge: 'GROUNDING',
      passed: candle.holds >= o.minHoldViolators && candle.p <= o.maxP,
      detail: `${candle.holds} held case(s) violate it (gate ≥ ${o.minHoldViolators}); exact p = ${candle.p.toExponential(2)} (gate ≤ ${o.maxP})`,
      stats: { holds: candle.holds, k: candle.k, p: candle.p, decidable: candle.decidable, decidable_holds: candle.decidable_holds, min_hold_violators: o.minHoldViolators, max_p: o.maxP },
    },
    {
      judge: 'NOVELTY',
      passed: newHolds >= o.minNewHolds,
      detail: `explains ${newHolds} hold(s) no earlier candle explains (gate ≥ ${o.minNewHolds})`,
      stats: { new_holds: newHolds, min_new_holds: o.minNewHolds },
    },
  ]
  const learned = candle.t !== undefined ? ` Learned tolerance t = ${candle.t}.` : candle.c !== undefined ? ` Learned constant c = ${candle.c}.` : ''
  return makeCounsel({
    kind: 'CANDLE',
    title: `Consider the rule \`${candle.id}\``,
    body: `The miner proposes \`${candle.id}\` (family ${candle.family}): ${candle.holds} held and ${candle.approved} approved case(s) violate it, of ${candle.decidable} decidable.${learned} It is a candle for a person to ratify, never a rule on its own; enforcing it needs a human to adopt the compiled ruleset.`,
    subject: {
      candle_id: candle.id,
      family: candle.family,
      spec: candle.spec,
      ...(candle.t !== undefined ? { t: candle.t } : {}),
      ...(candle.c !== undefined ? { c: candle.c } : {}),
      ...(candle.interval ? { interval: candle.interval } : {}),
      strict: candle.strict,
      violators: candle.violators,
    },
    provenance: { type: 'GENERATED', generator: report.engine, generator_version: report.mine_version, source_hash: report.data.table_hash },
    judges,
  })
}

/** Every candle in a mine report as COUNSEL, in acceptance order. */
export function counselFromReport(report: MineReport): Counsel[] {
  return report.candles.map(c => counselFromCandle(report, c))
}

export interface ReasonedOptions {
  strength: Strength
  /** The reasoning layer that produced the finding (it stands outside verify). */
  generator: string
  generator_version: string
  /** Extra judges the reasoning layer applied. EVIDENCED and BOUND are always run here. */
  judges?: JudgeResult[]
}

/**
 * A judgement-tier (REASONED) finding as an ADVISORY. It is never a VERDICT and never holds the action: people and agents
 * may proceed with the data. It is always shown with the evidence it rests on and a dispute path for that single finding.
 * Refuses a DETERMINISTIC claim (that finding belongs on the VERDICT channel) and an abstention (nothing to advise).
 */
export function counselFromReasoned(verdict: Verdict, claim_id: string, opts: ReasonedOptions): Counsel {
  const claim = verdict.claims.find(c => c.claim_id === claim_id)
  if (!claim) throw new ChannelViolation(`verdict ${verdict.verdict_id} has no claim ${claim_id}`)
  if (claim.tier === 'DETERMINISTIC') throw new ChannelViolation(`claim ${claim_id} is DETERMINISTIC: it is a VERDICT finding, not an advisory`)
  if (claim.outcome !== 'PASS' && claim.outcome !== 'FAIL') throw new ChannelViolation(`claim ${claim_id} abstained: there is no finding to advise on`)
  const bound = typeof verdict.input_hash === 'string' && isObj(verdict.ruleset) && deriveVerdictId(verdict.input_hash, verdict.ruleset, verdict.engine_version, typeof verdict.remedy_table_hash === 'string' ? verdict.remedy_table_hash : undefined) === verdict.verdict_id
  const judges: JudgeResult[] = [
    { judge: 'EVIDENCED', passed: claim.evidence.length > 0, detail: `the finding rests on ${claim.evidence.length} cited cell(s)`, stats: { evidence: claim.evidence.length } },
    { judge: 'BOUND', passed: bound, detail: bound ? 'the verdict it comes from is bound to its inputs (verdict_id re-derives)' : 'the verdict it comes from is not bound to its inputs' },
    ...(opts.judges ?? []),
  ]
  const label = opts.strength === 'strong' ? 'Strong advisory' : opts.strength === 'moderate' ? 'Advisory' : 'Note'
  return makeCounsel({
    kind: 'ADVISORY',
    strength: opts.strength,
    title: `${label}: ${claim.rule_name} ${claim.outcome === 'FAIL' ? 'did not hold' : 'held'} on \`${claim.field}\``,
    body: `${claim.explanation} This is a judgement-tier finding: advice, never a VERDICT. It does not hold the action; people and agents may proceed with the data. It is shown with the evidence it rests on so a person can dispute it.`,
    subject: {
      verdict_id: verdict.verdict_id,
      claim_id: claim.claim_id,
      rule_id: claim.rule_id,
      tier: claim.tier,
      outcome: claim.outcome,
      field: claim.field,
      asserted: claim.asserted,
      ...(claim.computation ? { expected: claim.computation.result } : {}),
    },
    evidence: claim.evidence,
    dispute: { verdict_id: verdict.verdict_id, claim_id: claim.claim_id, command: disputeCommand(verdict.verdict_id, claim.claim_id) },
    provenance: { type: 'GENERATED', generator: opts.generator, generator_version: opts.generator_version, source_hash: verdict.input_hash },
    judges,
  })
}

/** Every judgement-tier PASS/FAIL finding on a verdict as an ADVISORY, in claim order. The caller declares each strength. */
export function advisoriesFromVerdict(verdict: Verdict, opts: Omit<ReasonedOptions, 'strength'> & { strengthOf: (claim: ClaimVerdict) => Strength }): Counsel[] {
  return verdict.claims
    .filter(c => c.tier !== 'DETERMINISTIC' && (c.outcome === 'PASS' || c.outcome === 'FAIL'))
    .map(c => counselFromReasoned(verdict, c.claim_id, { strength: opts.strengthOf(c), generator: opts.generator, generator_version: opts.generator_version, ...(opts.judges ? { judges: opts.judges } : {}) }))
}

/** Render COUNSEL (Markdown). Labeled GENERATED and dismissible, with its judges; it never wears the VERDICT label. */
export function renderCounsel(c: Counsel): string {
  if (!isCounsel(c)) throw new ChannelViolation('not a well-formed COUNSEL item (or its content no longer matches its counsel_id)')
  const strength = c.strength === 'strong' ? ' · **STRONG ADVISORY**' : c.strength === 'moderate' ? ' · advisory' : c.strength === 'note' ? ' · note' : ''
  const lines = [
    `**COUNSEL**${strength} · GENERATED by ${c.provenance.generator} ${c.provenance.generator_version} · dismissible · counsel \`${c.counsel_id}\``,
    '',
    c.strength === 'strong' ? `### ⚠ ${c.title}` : `**${c.title}**`,
    '',
    c.body,
    '',
  ]
  if (c.evidence && c.evidence.length) {
    lines.push('The evidence it rests on:')
    for (const e of c.evidence) {
      const where = e.locator.kind === 'field' ? `${e.locator.source}:${e.locator.path}` : `span ${e.locator.source_hash.slice(0, 12)}…`
      lines.push(`- \`${where}\` = ${JSON.stringify(e.value)} · confidence ${e.confidence}`)
    }
    lines.push('')
  }
  lines.push('Why it was surfaced (the judges):', ...c.judges.map(j => `- ${j.passed ? '✓' : '✗'} ${j.judge}: ${j.detail}`), '')
  if (c.dispute) lines.push(`Dispute it: \`${c.dispute.command}\``, '')
  lines.push(`_Advice, not a finding: it does not hold the action. Generated from \`${c.provenance.source_hash.slice(0, 12)}…\`, not checked against a binding source. Dismiss freely._`, '')
  return lines.join('\n')
}

/** Render whichever channel the item speaks on, under its own label. Never promotes COUNSEL. */
export function renderChanneled(x: Verdict | Counsel): string {
  return channelOf(x) === 'COUNSEL' ? renderCounsel(x as Counsel) : renderVerdict(x)
}

/** Serialize under the item's own channel: a verdict is stamped VERDICT; counsel stays COUNSEL. Never promotes COUNSEL. */
export function serializeChanneled(x: Verdict | Counsel): string {
  if (channelOf(x) === 'COUNSEL') {
    if (!isCounsel(x)) throw new ChannelViolation('not a well-formed COUNSEL item (or its content no longer matches its counsel_id)')
    return JSON.stringify(x, null, 2)
  }
  return serializeVerdict(x)
}
